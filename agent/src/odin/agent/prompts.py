def render_state(session: Session, today: date) -> str:
    """Актуальное состояние диалога; обновляется перед каждым обращением к модели."""
    request = session.request
    lines = [
        "ТЕКУЩЕЕ СОСТОЯНИЕ",
        f"Сегодня: {today.isoformat()}, {WEEKDAYS[today.weekday()]}.",
        "Запрос: " + json.dumps(request_view(request), ensure_ascii=False),
        "Для поиска не хватает: " + (", ".join(request.missing) or "ничего") + ".",
        _plan_line(session, today),
        _cart_line(session),
    ]
    if session.order is not None:
        lines.append(f"Заказ: оформлен {session.order.id} (имитация оплаты).")
    return "\n".join(lines)


def _plan_line(session: Session, today: date) -> str:
    plan = session.plan
    if plan is None:
        return "План: не собран."
    line = (
        f"План: ревизия {plan.revision}, {plan.destination.name}, {plan.check_in.isoformat()}…"
        f"{plan.check_out.isoformat()}, итого {rub(plan.total_price_rub)}, "
        f"блокирующих проблем: {len(plan.errors)}."
    )
    outdated = session.outdated_slots(today)
    if outdated:
        parts = ", ".join(slot.value for slot in outdated)
        line += f" Запрос изменился, устарели части: {parts} — вызовите build_plan."
    return line


def _cart_line(session: Session) -> str:
    cart = session.cart
    if cart is None:
        return "Корзина: нет."
    shown = "показана пользователю" if cart.presented else "ещё не показана пользователю"
    return f"Корзина: {cart.status.value}, {rub(cart.total_price_rub)}, {shown}."
