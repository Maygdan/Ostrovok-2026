"""Ожидаемые ошибки предметной области. Их текст можно показать человеку или вернуть LLM."""


class DomainError(Exception):
    """Запрошенное действие невозможно; сообщение объясняет почему и что можно сделать."""


class MissingInformation(DomainError):
    """Не хватает данных от пользователя: агенту стоит уточнить, а не повторять попытку."""
